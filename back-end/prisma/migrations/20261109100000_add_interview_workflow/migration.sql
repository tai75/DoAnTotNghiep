CREATE TABLE `interviews` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `application_id` INTEGER NOT NULL,
  `recruiter_user_id` INTEGER NOT NULL,
  `round` INTEGER NOT NULL,
  `scheduled_start` DATETIME(3) NOT NULL,
  `scheduled_end` DATETIME(3) NOT NULL,
  `timezone` VARCHAR(100) NOT NULL,
  `mode` ENUM('ONLINE', 'ONSITE') NOT NULL,
  `location` VARCHAR(500) NULL,
  `meeting_url` VARCHAR(1000) NULL,
  `candidate_instructions` TEXT NULL,
  `recruiter_note` TEXT NULL,
  `candidate_response_note` TEXT NULL,
  `proposed_start` DATETIME(3) NULL,
  `proposed_end` DATETIME(3) NULL,
  `status` ENUM('PENDING_RESPONSE', 'CONFIRMED', 'RESCHEDULE_REQUESTED', 'DECLINED', 'CANCELLED', 'COMPLETED') NOT NULL DEFAULT 'PENDING_RESPONSE',
  `version` INTEGER NOT NULL DEFAULT 1,
  `request_key` CHAR(36) NOT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  UNIQUE INDEX `interviews_request_key_key`(`request_key`),
  UNIQUE INDEX `interviews_application_id_round_key`(`application_id`, `round`),
  INDEX `interviews_application_id_status_idx`(`application_id`, `status`),
  INDEX `interviews_recruiter_user_id_scheduled_start_idx`(`recruiter_user_id`, `scheduled_start`),
  INDEX `interviews_status_scheduled_start_idx`(`status`, `scheduled_start`),
  PRIMARY KEY (`id`),
  CONSTRAINT `interviews_application_id_fkey` FOREIGN KEY (`application_id`) REFERENCES `applications`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `interviews_recruiter_user_id_fkey` FOREIGN KEY (`recruiter_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
