import { expect, test } from '@playwright/test'

const candidateEmail = process.env.FEATURE24_CANDIDATE_EMAIL
const recruiterEmail = process.env.FEATURE24_RECRUITER_EMAIL
const password = process.env.FEATURE24_PASSWORD
const applicationId = Number(process.env.FEATURE24_APPLICATION_ID)

if (!candidateEmail || !recruiterEmail || !password || !Number.isInteger(applicationId) || applicationId < 1) throw new Error('FEATURE24 browser environment is incomplete')

async function browserLogin(page, email) {
  await page.goto('/login')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Mật khẩu').fill(password)
  await page.locator('form.auth-form button[type="submit"]').click()
  await expect(page).not.toHaveURL(/\/login/)
}

async function expectResponsiveVietnamese(page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const visibleText = await page.locator('body').innerText()
  expect(visibleText).not.toMatch(/Ã.|Â.|Ä.|á»|áº/)
}

test('Recruiter → Candidate → Recruiter workflow, reload, responsive and Vietnamese', async ({ browser }) => {
  const recruiterContext = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: 'vi-VN', timezoneId: 'Asia/Ho_Chi_Minh' })
  const recruiterPage = await recruiterContext.newPage()
  const recruiterErrors = []
  recruiterPage.on('pageerror', (error) => recruiterErrors.push(error.message))
  await browserLogin(recruiterPage, recruiterEmail)
  await recruiterPage.goto('/recruiter/interviews')
  await expect(recruiterPage.getByRole('heading', { name: 'Quản lý lịch phỏng vấn' })).toBeVisible()
  await recruiterPage.getByRole('button', { name: '+ Đặt lịch' }).click()
  let formDialog = recruiterPage.getByRole('dialog', { name: 'Đặt lịch phỏng vấn' })
  await expect(formDialog).toBeVisible()
  const selectedOption = await formDialog.getByLabel('Hồ sơ ứng tuyển').selectOption(String(applicationId))
  expect(selectedOption).toEqual([String(applicationId)])
  const applicationLabel = await formDialog.getByLabel('Hồ sơ ứng tuyển').locator('option:checked').textContent()
  await formDialog.getByLabel('Bắt đầu').fill('2031-10-10T09:00')
  await formDialog.getByLabel('Kết thúc').fill('2031-10-10T10:00')
  await formDialog.getByLabel('Liên kết họp (HTTPS)').fill('https://meet.example.test/feature24-browser')
  await formDialog.getByLabel('Hướng dẫn cho ứng viên').fill('Chuẩn bị hồ sơ và vào phòng họp trước 5 phút.')
  await formDialog.getByLabel('Ghi chú nội bộ').fill('Không được hiển thị cho ứng viên.')
  const createResponsePromise = recruiterPage.waitForResponse((response) => response.url().endsWith('/api/interviews/recruiter') && response.request().method() === 'POST')
  await formDialog.getByRole('button', { name: 'Lưu lịch phỏng vấn' }).click()
  const createResponse = await createResponsePromise
  expect(createResponse.status()).toBe(201)
  const interview = (await createResponse.json()).data
  await expect(recruiterPage.getByText('Đã tạo lịch phỏng vấn.')).toBeVisible()
  await expect(recruiterPage.getByRole('dialog', { name: 'Chi tiết lịch phỏng vấn' })).toBeVisible()
  await expectResponsiveVietnamese(recruiterPage)
  await recruiterPage.getByRole('button', { name: 'Đóng', exact: true }).click()
  await recruiterPage.reload()
  await expect(recruiterPage.getByText(applicationLabel.split(' · ').at(-1), { exact: true }).first()).toBeVisible()

  const candidateContext = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'vi-VN', timezoneId: 'Asia/Ho_Chi_Minh' })
  const candidatePage = await candidateContext.newPage()
  const candidateErrors = []
  candidatePage.on('pageerror', (error) => candidateErrors.push(error.message))
  await browserLogin(candidatePage, candidateEmail)
  await candidatePage.goto('/interviews')
  await expect(candidatePage.getByRole('heading', { name: 'Lịch phỏng vấn' })).toBeVisible()
  await candidatePage.getByRole('button', { name: /Thông báo/ }).click()
  const notificationDialog = candidatePage.getByRole('dialog', { name: 'Thông báo' })
  await expect(notificationDialog.getByText('Bạn có lịch phỏng vấn mới', { exact: true }).first()).toBeVisible()
  await notificationDialog.getByRole('button', { name: 'Đóng thông báo' }).click()
  await candidatePage.goto(`/interviews/${interview.id}`)
  let candidateDetail = candidatePage.getByRole('dialog', { name: 'Chi tiết lịch phỏng vấn' })
  await expect(candidateDetail).toBeVisible()
  await expect(candidateDetail.getByText('Trực tuyến', { exact: true })).toBeVisible()
  await expect(candidateDetail.getByRole('link', { name: 'Mở liên kết phỏng vấn' })).toHaveAttribute('href', 'https://meet.example.test/feature24-browser')
  await expect(candidateDetail.getByText('Không được hiển thị cho ứng viên.')).toHaveCount(0)
  const mobileBox = await candidateDetail.boundingBox()
  expect(mobileBox.width).toBeLessThanOrEqual(390)
  await expectResponsiveVietnamese(candidatePage)
  await candidateDetail.getByRole('button', { name: 'Xác nhận tham gia' }).click()
  const confirmDialog = candidatePage.getByRole('dialog', { name: 'Xác nhận tham gia' })
  const confirmResponsePromise = candidatePage.waitForResponse((response) => response.url().endsWith(`/api/interviews/candidate/${interview.id}/confirm`))
  await confirmDialog.getByRole('button', { name: 'Xác nhận tham gia' }).click()
  expect((await confirmResponsePromise).status()).toBe(200)
  await expect(candidatePage.getByText('Phản hồi lịch phỏng vấn đã được lưu.')).toBeVisible()
  await candidatePage.reload()
  candidateDetail = candidatePage.getByRole('dialog', { name: 'Chi tiết lịch phỏng vấn' })
  await expect(candidateDetail.getByText('Đã xác nhận', { exact: true })).toBeVisible()

  await recruiterPage.goto(`/recruiter/interviews/${interview.id}`)
  let recruiterDetail = recruiterPage.getByRole('dialog', { name: 'Chi tiết lịch phỏng vấn' })
  await expect(recruiterDetail.getByText('Đã xác nhận', { exact: true })).toBeVisible()
  await recruiterDetail.getByRole('button', { name: 'Đổi lịch' }).click()
  formDialog = recruiterPage.getByRole('dialog', { name: 'Đổi lịch phỏng vấn' })
  await formDialog.getByLabel('Bắt đầu').fill('2031-10-11T14:00')
  await formDialog.getByLabel('Kết thúc').fill('2031-10-11T15:00')
  await formDialog.getByLabel('Tại địa điểm').check()
  await formDialog.getByRole('textbox', { name: 'Địa điểm', exact: true }).fill('Tầng 8, 123 Nguyễn Huệ, Quận 1')
  const updateResponsePromise = recruiterPage.waitForResponse((response) => response.url().endsWith(`/api/interviews/recruiter/${interview.id}`) && response.request().method() === 'PATCH')
  await formDialog.getByRole('button', { name: 'Lưu lịch phỏng vấn' }).click()
  expect((await updateResponsePromise).status()).toBe(200)
  await expect(recruiterPage.getByText('Đã cập nhật lịch phỏng vấn.')).toBeVisible()

  await candidatePage.goto(`/interviews/${interview.id}`)
  candidateDetail = candidatePage.getByRole('dialog', { name: 'Chi tiết lịch phỏng vấn' })
  await expect(candidateDetail.getByText('Chờ phản hồi', { exact: true })).toBeVisible()
  await expect(candidateDetail.getByText('Tại địa điểm', { exact: true })).toBeVisible()
  await expect(candidateDetail.getByText('Tầng 8, 123 Nguyễn Huệ, Quận 1')).toBeVisible()
  await candidatePage.setViewportSize({ width: 1440, height: 900 })
  await expectResponsiveVietnamese(candidatePage)
  const desktopCandidateBox = await candidateDetail.boundingBox()
  expect(desktopCandidateBox.width).toBeLessThanOrEqual(1440)

  await recruiterPage.setViewportSize({ width: 390, height: 844 })
  await recruiterPage.goto(`/recruiter/interviews/${interview.id}`)
  recruiterDetail = recruiterPage.getByRole('dialog', { name: 'Chi tiết lịch phỏng vấn' })
  await expect(recruiterDetail).toBeVisible()
  await expectResponsiveVietnamese(recruiterPage)
  const mobileRecruiterBox = await recruiterDetail.boundingBox()
  expect(mobileRecruiterBox.width).toBeLessThanOrEqual(390)
  await recruiterDetail.getByRole('button', { name: 'Hủy lịch' }).click()
  const cancelDialog = recruiterPage.getByRole('dialog', { name: 'Hủy lịch phỏng vấn?' })
  await cancelDialog.getByLabel('Lý do').fill('Hủy lịch trong kiểm thử FEATURE24.')
  const cancelResponsePromise = recruiterPage.waitForResponse((response) => response.url().endsWith(`/api/interviews/recruiter/${interview.id}/cancel`))
  await cancelDialog.getByRole('button', { name: 'Xác nhận hủy' }).click()
  expect((await cancelResponsePromise).status()).toBe(200)
  await expect(recruiterPage.getByText('Đã hủy lịch phỏng vấn.')).toBeVisible()
  await recruiterPage.reload()
  await expect(recruiterPage.getByRole('dialog', { name: 'Chi tiết lịch phỏng vấn' }).getByText('Đã hủy', { exact: true })).toBeVisible()

  await candidatePage.setViewportSize({ width: 390, height: 844 })
  await candidatePage.goto(`/interviews/${interview.id}`)
  await expect(candidatePage.getByRole('dialog', { name: 'Chi tiết lịch phỏng vấn' }).getByText('Đã hủy', { exact: true })).toBeVisible()
  await expectResponsiveVietnamese(candidatePage)

  expect(recruiterErrors).toEqual([])
  expect(candidateErrors).toEqual([])
  await Promise.all([recruiterContext.close(), candidateContext.close()])
})
